"""The search-evaluation corpus (design M2 §8.2, §8.3): synthetic, deterministic, gold units exist."""
import hashlib
import re
from collections import Counter

import pytest

from fixtures import RESERVED_DOMAINS, RESERVED_TLD, SENTINEL
from fixtures import corpus as corpus_module
from workmcp import parsers

EMAIL = re.compile(r'[A-Za-z0-9._%+-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)')
PHONE = re.compile(r'\b0\d{1,2}-\d{3,4}-\d{4}\b')


@pytest.fixture(scope='module')
def corpus():
    return corpus_module.build()


@pytest.fixture(scope='module')
def parsed(corpus):
    """rel_path -> [(unit, text)] as the parsers read the generated bytes."""
    out = {}
    for topic in corpus.topics:
        data, _ = corpus_module.document(topic)
        result = parsers.parse(data, '.' + topic.fmt, parsers.Limits())
        assert result.status == 'ok', (topic.rel_path, result.status, result.error)
        out[topic.rel_path] = [(unit.unit, unit.text) for unit in result.units]
    return out


def test_corpus_is_synthetic_and_deterministic(corpus, tmp_path):
    again = corpus_module.build()
    assert again == corpus
    assert corpus_module.build(seed=8) != corpus
    assert len(corpus.topics) == corpus_module.TOPIC_COUNT
    assert Counter(t.fmt for t in corpus.topics) == Counter(corpus_module.FORMAT_COUNTS)
    assert len({t.sentinel for t in corpus.topics}) == 60 and len({t.project_code for t in corpus.topics}) == 60
    first = {p: hashlib.sha256((tmp_path/'a'/p).read_bytes()).hexdigest()
             for p in corpus_module.write(corpus, tmp_path/'a')}
    second = {p: hashlib.sha256((tmp_path/'b'/p).read_bytes()).hexdigest()
              for p in corpus_module.write(again, tmp_path/'b')}
    assert first == second and len(first) == 60
    for topic in corpus.topics:
        text = '\n'.join(corpus.unit_texts[topic.rel_path])
        assert SENTINEL in text, topic.rel_path                          # rule 2
        assert topic.sentinel in text
        for match in EMAIL.finditer(text):                               # rule 1: reserved domains only
            domain = match.group(1).lower()
            assert domain in RESERVED_DOMAINS or domain.endswith(RESERVED_TLD), match.group(0)
        assert not PHONE.search(text)
        assert 8 <= len(topic.body_sentences) <= 12
        assert all(customer.startswith('가상 거래처 ') for customer in (topic.customer,))
    # A topic sentinel appears in exactly one document.
    for topic in corpus.topics:
        holders = [p for p, texts in corpus.unit_texts.items() if any(topic.sentinel in t for t in texts)]
        assert holders == [topic.rel_path]


def test_units_written_match_the_parsers(corpus, parsed):
    for path, units in parsed.items():
        assert [unit for unit, _ in units] == list(corpus.units[path]), path
        assert [text for _, text in units] == list(corpus.unit_texts[path]), path


def test_queries_have_gold_units_that_exist(corpus, parsed):
    found = corpus_module.queries(corpus)
    counts = Counter(q.category for q in found)
    assert counts == Counter(corpus_module.CATEGORY_COUNTS)
    assert 115 <= len(found) <= 125
    assert len({q.id for q in found}) == len(found) and len({q.text for q in found}) == len(found)
    for query in found:
        assert query.text.strip() and len(query.text) <= 1000
        if query.category == 'Q9_absent':
            assert query.gold == () and query.gold_docs == ()
            blob = '\n'.join(t for texts in corpus.unit_texts.values() for t in texts)
            assert query.text not in blob
            continue
        assert query.gold, query
        assert query.gold_docs == tuple(sorted({p for p, _ in query.gold}))
        if query.category != 'Q8_two_chars':
            assert 1 <= len(query.gold_docs) <= 3, query
        for path, unit in query.gold:
            assert any(u == unit for u, _ in parsed[path]), (query.id, path, unit)


def test_categories_are_built_as_described(corpus):
    by_cat = {}
    for query in corpus.queries:
        by_cat.setdefault(query.category, []).append(query)
    blob = '\n'.join(t for texts in corpus.unit_texts.values() for t in texts).casefold()
    for query in by_cat['Q1_phrase']:          # verbatim excerpt
        assert 5 <= len(query.text) <= 12 and query.text.casefold() in blob
    for query in by_cat['Q3_acronym']:         # the other form of the acronym than the document's
        topic = next(t for t in corpus.topics if t.rel_path in query.gold_docs and t.customer in query.text)
        other = topic.acronym_ko if topic.acronym_in_doc == topic.acronym else topic.acronym
        assert other in query.text
    for query in by_cat['Q8_two_chars']:
        assert len(query.text) == 2
    assert all(q.text.endswith('?') for q in by_cat['Q7_question'])
